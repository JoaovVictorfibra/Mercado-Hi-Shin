    private void PagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_PagarActionPerformed
        RegistroVenda rv = new RegistroVenda();
        String nome = null;
        try {
            //valor total da compra
        String totalTexto = lblTotalCompra.getText().replace("R$", "").trim().replace(",", ".");
        if (totalTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "O valor total da compra está vazio.");
            return;
        }
        //converte vlor para numero
        double total = Double.parseDouble(totalTexto);

        //setando  forma de pagamento
        if(jComboBox1.getSelectedItem().toString() == "Forma de Pagamento"){
            JOptionPane.showMessageDialog(null, "Selecione metodo de pagaemento", "Erro",JOptionPane.ERROR_MESSAGE);
        }else{
            rv.setForma_Pagamento(jComboBox1.getSelectedItem().toString());
        
            rv.setTotal(total);
        
            //obtendo o nome do cliente
            nome = JOptionPane.showInputDialog(null, "Informe o seu nome:");
        }
        if (nome == null || nome.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nome não pode estar vazio.");
            return;
        }

        rv.setNome(nome.trim());

        // Aqui você salva o registro no banco
        RegistroVendaJPA.cadastrar(rv);
        
        // Limpa a tabela de venda
        DefaultTableModel modelo = (DefaultTableModel) jTable2.getModel();
        modelo.setRowCount(0);

        // Zera o valor da compra
        lblTotalCompra.setText("");

        JOptionPane.showMessageDialog(this, "Compra registrada com sucesso!");

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Erro ao converter o valor da compra.");
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Erro ao registrar a venda: " + ex.getMessage());
    }
        
    }//GEN-LAST:event_PagarActionPerformed

