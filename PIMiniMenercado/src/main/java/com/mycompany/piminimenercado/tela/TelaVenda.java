    private DefaultTableModel montarTabela(List<Produto> lista){
        String[] colunas = {"Codigo", "Nome", "Preco"};
        
        DefaultTableModel tabela = new DefaultTableModel();
        
        tabela.setColumnIdentifiers(colunas);
        for(Produto p: lista){
            Object[] linha ={
                p.getCodigo(),
                p.getNome(),
                p.getPreco()
            };
            tabela.addRow(linha);
        }
        return tabela;
    }
    
    private DefaultTableModel montarTabela1(List<Produto> lista){
        String[] colunas = {"Nome", "Codigo", "Quantidade", "Preco", "total"};
        int quantidade = 0;
        DefaultTableModel tabela = new DefaultTableModel();
        tabela.setColumnIdentifiers(colunas);
        
        for(Produto p: lista){
            double total = quantidade * p.getPreco();
            Object[] linha = {
                p.getCodigo(),
                p.getNome(),
                quantidade,
                p.getPreco(),
                total
            };
            tabela.addRow(linha);
        }
        return tabela;
    } 
    
    public void calcularTotalCompra(){
        DefaultTableModel modelo = (DefaultTableModel) jTable2.getModel();
        double soma = 0.0;
        
        for(int i = 0; i < modelo.getRowCount(); i++){
            if(modelo.getColumnCount() >4){
                Object valorObj = modelo.getValueAt(i, 4);
                if(valorObj != null && valorObj instanceof Number){
                    soma += ((Number) valorObj).doubleValue();
                }else if(valorObj != null){
                    try{
                        soma += Double.parseDouble(valorObj.toString());
                    }catch(NumberFormatException e){
                        
                    }
                }
            }
        }
        lblTotalCompra.setText(String.format("%.2f", soma));
    }
    
    private void adicionarProduto(){
    int linhaSelecionada = jTable1.getSelectedRow();
        try{
        if(linhaSelecionada != -1){
            DefaultTableModel modeloBuscar = (DefaultTableModel) jTable1.getModel();
            DefaultTableModel modeloLista = (DefaultTableModel) jTable2.getModel();
            
            Object codigo = modeloBuscar.getValueAt(linhaSelecionada, 0);
        Object nome = modeloBuscar.getValueAt(linhaSelecionada, 1);
        double preco = (double) modeloBuscar.getValueAt(linhaSelecionada, 2);
        int quantidade = Integer.parseInt(jTextQuantidade.getText());
        double total = preco * quantidade;

        modeloLista.addRow(new Object[]{codigo, nome, quantidade, preco, total});
            
            
            }else{
            JOptionPane.showMessageDialog(null, "Selecione um produto para adicionar a lista de compras");
        }
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, "Necessario colocar a quantidade do produto");
    }
    }
